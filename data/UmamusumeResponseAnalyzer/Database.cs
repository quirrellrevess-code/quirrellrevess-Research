	private static async Task<T> DeserializeAsync<T>(string filepath, JsonSerializerSettings settings = null)
	{
		if (File.Exists(filepath))
		{
			try
			{
				await using FileStream fileStream = new FileStream(filepath, FileMode.Open, FileAccess.Read, FileShare.Read, 16384, useAsync: true);
				T result;
				await using (BrotliStream stream = new BrotliStream(fileStream, CompressionMode.Decompress))
				{
					using StreamReader reader = new StreamReader(stream, Encoding.UTF8);
					using JsonTextReader reader2 = new JsonTextReader(reader);
					T val = ((settings == null) ? _serializer : JsonSerializer.Create(settings)).Deserialize<T>(reader2);
					if (val != null)
					{
						result = val;
						goto IL_01a6;
					}
					AnsiConsole.MarkupLine(global::UmamusumeResponseAnalyzer.Localization.Database.I18N_LoadFail, Path.GetFileName(filepath));
				}
				goto end_IL_0055;
				IL_01a6:
				return result;
				end_IL_0055:;
			}
			catch (InvalidDataException)
			{
				AnsiConsole.MarkupLine(global::UmamusumeResponseAnalyzer.Localization.Database.I18N_DecompressError, Path.GetFileName(filepath));
			}
			catch (Exception)
			{
				AnsiConsole.MarkupLine(global::UmamusumeResponseAnalyzer.Localization.Database.I18N_LoadFail, Path.GetFileName(filepath));
			}
		}
		else
		{
			AnsiConsole.MarkupLine(global::UmamusumeResponseAnalyzer.Localization.Database.I18N_NotExist, Path.GetFileName(filepath));
		}
		return default;
	}

